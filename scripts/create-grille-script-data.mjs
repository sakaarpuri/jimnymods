// Build compact, normalized lettering meshes from a historical site GLB and
// the Allura-based mesh made by modeling/build_alt_script.py. No model is edited.
import {readFile,writeFile} from 'node:fs/promises';
import {GLTFLoader} from 'three/addons/loaders/GLTFLoader.js';
import {MeshoptDecoder} from 'three/addons/libs/meshopt_decoder.module.js';
import {Box3,Vector3} from 'three';

const [oldPath,newPath]=process.argv.slice(2);
if(!oldPath||!newPath)throw new Error('Pass the historical and newly exported GLB paths');
async function meshData(path,name){
 const data=await readFile(path),scene=(await new GLTFLoader().setMeshoptDecoder(MeshoptDecoder).parseAsync(data.buffer.slice(data.byteOffset,data.byteOffset+data.byteLength),'')).scene;
 scene.updateMatrixWorld(true);let mesh=name?scene.getObjectByName(name):null;if(!mesh)scene.traverse(o=>{if(!mesh&&o.isMesh)mesh=o;});if(!mesh?.isMesh)throw new Error(`Missing lettering in ${path}`);
 const geometry=mesh.geometry.clone();geometry.applyMatrix4(mesh.matrixWorld);geometry.computeBoundingBox();const box=geometry.boundingBox,centre=box.getCenter(new Vector3()),size=box.getSize(new Vector3());
 geometry.translate(-centre.x,-centre.y,-centre.z);geometry.scale(1/size.x,1/size.y,1/size.z);
 const attr=geometry.attributes.position,normals=geometry.attributes.normal,indices=geometry.index;
 const vertices=new Float32Array(attr.count*6);for(let i=0;i<attr.count;i++){vertices.set([attr.getX(i),attr.getY(i),attr.getZ(i),normals.getX(i),normals.getY(i),normals.getZ(i)],i*6);}
 const triangles=indices?Uint32Array.from(indices.array):Uint32Array.from({length:attr.count},(_,i)=>i);
 const result={vertexCount:attr.count,vertices:Buffer.from(vertices.buffer).toString('base64'),indices:Buffer.from(triangles.buffer).toString('base64')};geometry.dispose();return result;
}
const old=await meshData(oldPath,'ScriptGrille__GrilleLettering'),loop=await meshData(newPath);
await writeFile('src/grille-script-data.js',`// Generated by scripts/create-grille-script-data.mjs. Allura: SIL OFL 1.1.\nexport default ${JSON.stringify({heritage:old,loop})};\n`);
console.log('Lettering vertices:',old.vertexCount,loop.vertexCount);
